import type { Report } from '../types.js';
import { bugfixRate, busFactorText, headline, hotspots, knowledgeRisks, num, owner, pct, window } from './format.js';

const cell = (s: string) => s.replace(/\|/g, '\\|');

export function renderMarkdown(report: Report, opts: { top?: number } = {}): string {
  const r = report.repo;
  const lines: string[] = [];
  lines.push(`## 🔥 repoheat: ${r.name}${r.scope ? ` / ${r.scope}` : ''}`);
  lines.push('');
  lines.push(
    `> ${headline(report)} Bus factor: **${busFactorText(report)}**. ` +
      `Bug-fix commits: **${pct(bugfixRate(report))}**. ` +
      `_${window(report)} · ${num(report.totals.commits)} commits · ${num(report.totals.authors)} authors · ${num(report.totals.files)} files_`,
  );
  lines.push('');

  const top = hotspots(report, opts.top ?? 10);
  if (top.length) {
    lines.push('### Hotspots');
    lines.push('');
    lines.push('Files that change often **and** are complex. Bugs cluster here: change them carefully, add tests first, and refactor when you can.');
    lines.push('');
    lines.push('| # | File | Score | Commits | Complexity | Bug fixes | Main author |');
    lines.push('|--:|------|------:|--------:|-----------:|----------:|-------------|');
    top.forEach((f, i) => {
      const who = owner(f);
      const ownerCell = who && who !== 'shared' ? `${cell(who)} (${pct(f.topAuthorShare)})` : who;
      lines.push(
        `| ${i + 1} | \`${cell(f.path)}\` | ${f.score} | ${f.commits} | ${num(f.complexity)} | ${f.bugfixes} | ${ownerCell} |`,
      );
    });
    lines.push('');
  }

  const risks = knowledgeRisks(report);
  if (risks.length) {
    lines.push('### Knowledge risk');
    lines.push('');
    for (const f of risks) lines.push(`- \`${f.path}\`: ${f.topAuthor} made ${pct(f.topAuthorShare)} of the changes`);
    lines.push('');
  }

  if (report.couplings.length) {
    lines.push('### Hidden coupling');
    lines.push('');
    lines.push('When you change one of these files, check the other one too.');
    lines.push('');
    for (const c of report.couplings.slice(0, 10)) {
      lines.push(`- \`${c.a}\` ⇄ \`${c.b}\`: changed together ${c.shared}× (${pct(c.degree)})`);
    }
    lines.push('');
  }

  lines.push(`<sub>Generated by [repoheat](https://github.com/ebxc-7s13/repoheat) v${report.tool.version}</sub>`);
  lines.push('');
  return lines.join('\n');
}
